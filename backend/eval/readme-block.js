/**
 * Regenerate the README block between <!-- RESULTS:START --> and <!-- RESULTS:END -->
 * from results/latest.json (eval) and results/tests/latest.json (test + coverage gate).
 *
 *   node eval/readme-block.js
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const pct = (x) => (x === null || x === undefined ? 'n/a' : (x * 100).toFixed(1));
const fmt = (m) => (m ? `${pct(m.value)} [${pct(m.ci_low)}–${pct(m.ci_high)}]` : 'n/a');
const readJson = async (p) => JSON.parse(await fs.readFile(p, 'utf8'));

export async function renderBlock() {
  const latest = await readJson(path.join(ROOT, 'results', 'latest.json'));
  const dir = path.join(ROOT, latest.path);
  const manifest = await readJson(path.join(dir, 'manifest.json'));
  const { metrics, power, regression_gate: gate } = await readJson(path.join(dir, 'metrics.json'));
  const L = [];
  L.push(`Generated by \`node eval/readme-block.js\` from run \`${manifest.run_id}\` (git ${manifest.git_sha?.slice(0, 7)}${manifest.git_dirty ? ', dirty tree' : ''}; \`${manifest.command}\`). Full report: [\`${latest.path}/report.md\`](./${latest.path}/report.md). Values in %, 95% bootstrap CI; answers from the extractive (no-LLM) provider with the app refusal gates.`, '');
  L.push('| Split | Run | hit@5 | Answer acc. | Refusal acc. | Citation acc. | p95 latency (ms) |', '|---|---|---|---|---|---|---|');
  for (const split of ['test', 'syn-test']) {
    for (const r of ['bm25', 'vector:local', 'hybrid:local', 'hybrid:minilm']) {
      const g = (k) => metrics[`${split}/${r}/${k}`];
      if (!g('hit@5')) continue;
      L.push(`| ${split === 'test' ? 'hand-written test' : 'SYNTHETIC test'} | ${r} | ${fmt(g('hit@5'))} | ${fmt(g('answer_accuracy'))} | ${g('refusal_accuracy') ? fmt(g('refusal_accuracy')) : '—'} | ${fmt(g('citation_accuracy'))} | ${g('latency_p95_ms').value.toFixed(1)} |`);
    }
  }
  L.push('', `Power: detecting a ${power.target_delta * 100}-point hit@5 difference (${power.comparison}) needs n = ${power.required_n}; hand-written test has n = ${power.achieved_n.hand_written_test}, synthetic test n = ${power.achieved_n.synthetic_test}.`);
  L.push(`Regression gate: ${gate.filter((g) => g.pass).length}/${gate.length} floors met (eval/thresholds.json).`);
  try {
    const t = await readJson(path.join(ROOT, 'results', 'tests', 'latest.json'));
    L.push(`Tests (${t.generated_at.slice(0, 10)}, \`${t.command}\`): ${t.pass}/${t.tests} passed; line coverage ${t.coverage.all.lines}% overall, critical modules ${t.critical.map((c) => `${c.file} ${c.lines}%`).join(', ')}.`);
  } catch {
    /* no test summary yet */
  }
  return L.join('\n');
}

export async function updateReadme() {
  const p = path.join(ROOT, 'README.md');
  const readme = await fs.readFile(p, 'utf8');
  const start = '<!-- RESULTS:START -->';
  const end = '<!-- RESULTS:END -->';
  if (!readme.includes(start) || !readme.includes(end)) throw new Error('README is missing the RESULTS markers');
  const block = await renderBlock();
  const next = readme.slice(0, readme.indexOf(start) + start.length) + '\n' + block + '\n' + readme.slice(readme.indexOf(end));
  await fs.writeFile(p, next);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  updateReadme().then(() => console.log('README results block updated'));
}
